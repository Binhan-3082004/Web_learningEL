-- Identity Service database (Tuần 4-5)
SET NAMES utf8mb4;
SET CHARACTER SET utf8mb4;
CREATE DATABASE IF NOT EXISTS identity_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE identity_db;

CREATE TABLE IF NOT EXISTS Users (
  Id           INT AUTO_INCREMENT PRIMARY KEY,
  Email        VARCHAR(256) NOT NULL UNIQUE,
  UserName     VARCHAR(100) NOT NULL UNIQUE,
  PasswordHash VARCHAR(255) NOT NULL,            -- bcrypt
  FullName     VARCHAR(100) NOT NULL,
  PhoneNumber  VARCHAR(20)  NULL,
  EnglishLevel VARCHAR(10)  NOT NULL DEFAULT 'A1',
  IsActive     TINYINT(1)   NOT NULL DEFAULT 1,  -- khóa/mở khóa tài khoản
  CreatedAt    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Roles (
  Id   INT AUTO_INCREMENT PRIMARY KEY,
  Name VARCHAR(50) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS UserRoles (
  UserId INT NOT NULL,
  RoleId INT NOT NULL,
  PRIMARY KEY (UserId, RoleId),
  FOREIGN KEY (UserId) REFERENCES Users(Id) ON DELETE CASCADE,
  FOREIGN KEY (RoleId) REFERENCES Roles(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS RefreshTokens (
  Id          INT AUTO_INCREMENT PRIMARY KEY,
  UserId      INT NOT NULL,
  Token       VARCHAR(256) NOT NULL UNIQUE,      -- lưu SHA-256 của token, không lưu token gốc
  ExpiresAt   DATETIME NOT NULL,
  RevokedAt   DATETIME NULL,
  CreatedByIp VARCHAR(50) NULL,
  CreatedAt   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (UserId) REFERENCES Users(Id) ON DELETE CASCADE,
  INDEX idx_refresh_user (UserId)
) ENGINE=InnoDB;

INSERT IGNORE INTO Roles (Name) VALUES ('user'), ('admin');
